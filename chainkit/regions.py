def t(region, pal_addr):
    """Address in `region` of what is at `pal_addr` in the PAL build."""
    m = region["map"]
    if m is None:
        return pal_addr
    try:
        return m[pal_addr]
    except KeyError:
        raise KeyError("no %s address for PAL %#x" % (region["key"], pal_addr))
